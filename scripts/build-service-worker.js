#!/usr/bin/env node
/**
 * Builds service-worker.js with CACHE_VERSION and list of files to cache.
 * Run: node scripts/build-service-worker.js
 * Output: service-worker.js (project root)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'service-worker.js');

// Version: timestamp for cache busting on deploy
const VERSION = process.env.SW_VERSION || Date.now().toString(36);

// Directories and patterns to include (relative to ROOT)
const INCLUDE = [
  'index.html',
  'manifest.json',
  'css/**/*.css',
  'js/**/*.js',
  'js/heroes/**/*.js',
  'js/net/**/*.js',
  'locales/**/*.json',
  'sounds/**/*.wav'
];

// Exclude dev/build scripts
const EXCLUDE = [
  'scripts/',
  '.cursor/',
  '.claude/',
  'node_modules/',
  'generate-dota-sfx'
];

function walkDir(dir, base = '', extFilter = null) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const rel = path.join(base, e.name);
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (!EXCLUDE.some(x => rel.startsWith(x) || rel.includes(x))) {
        files.push(...walkDir(full, rel, extFilter));
      }
    } else if (e.isFile()) {
      if (extFilter && !rel.endsWith(extFilter)) continue;
      if (!EXCLUDE.some(x => rel.startsWith(x) || rel.includes(x))) {
        files.push(rel.replace(/\\/g, '/'));
      }
    }
  }
  return files;
}

function collectFiles() {
  const files = new Set();
  for (const pattern of INCLUDE) {
    if (pattern.includes('*')) {
      const parts = pattern.split('/');
      const dirPart = parts[0];
      const ext = /\.(css|js|json|wav)$/.test(pattern) ? pattern.match(/\.(css|js|json|wav)$/)[0] : null;
      const dir = path.join(ROOT, dirPart);
      if (fs.existsSync(dir) && fs.statSync(dir).isDirectory()) {
        walkDir(dir, dirPart, ext).forEach(f => files.add(f));
      }
    } else {
      const full = path.join(ROOT, pattern);
      if (fs.existsSync(full)) files.add(pattern);
    }
  }
  return [...files].sort();
}

const FILES = collectFiles();

const SW_TEMPLATE = `// Generated by scripts/build-service-worker.js — do not edit by hand
const CACHE_VERSION = '${VERSION}';
const CACHE_NAME = 'crimson-lane-v' + CACHE_VERSION;

const FILES_TO_CACHE = [
${FILES.map(f => "  './" + f + "'").join(',\n')}
];

self.addEventListener('install', (ev) => {
  ev.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(FILES_TO_CACHE))
      .then(() => self.skipWaiting())
      .catch((err) => console.warn('SW install cache addAll failed:', err))
  );
});

self.addEventListener('activate', (ev) => {
  ev.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith('crimson-lane-') && k !== CACHE_NAME).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (ev) => {
  if (ev.request.method !== 'GET') return;
  ev.respondWith(
    caches.match(ev.request).then((cached) => cached || fetch(ev.request))
  );
});
`;

fs.writeFileSync(OUT, SW_TEMPLATE, 'utf8');
console.log('Wrote service-worker.js (version: %s, %d files)', VERSION, FILES.length);
